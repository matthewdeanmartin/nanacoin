// Build output only: never alter Angular source or the standalone deployment.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { resolve, relative, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const input = resolve(root, '../nanacoin/angular/dist/nanacoin-web/browser');
const output = resolve(root, '.embuild/web');
mkdirSync(output, { recursive: true });
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.ico': 'image/x-icon', '.svg': 'image/svg+xml',
  '.png': 'image/png', '.webp': 'image/webp', '.woff2': 'font/woff2', '.ttf': 'font/ttf', '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8' };
const entries = [];
const ca = readFileSync(resolve(root, 'certs/home-ca.der'));
const fingerprint = createHash('sha256').update(ca).digest('hex').toUpperCase().match(/../g).join(':');
writeFileSync(resolve(output, 'trust.html'), readFileSync(resolve(root, 'assets/trust.html'), 'utf8').replace('@@FINGERPRINT@@', fingerprint));
writeFileSync(resolve(output, 'home-ca.der'), ca);
function walk(dir) {
  for (const item of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = resolve(dir, item.name);
    if (item.isDirectory()) { walk(path); continue; }
    if (!item.isFile()) throw new Error(`Not a regular asset: ${path}`);
    const name = relative(input, path).replaceAll('\\', '/');
    if (!/^[a-zA-Z0-9_./-]+$/.test(name) || !types[extname(name)]) throw new Error(`Unsupported asset: ${name}`);
    let data = readFileSync(path);
    if (name === 'index.html') {
      const html = data.toString();
      const tag = /<meta\s+name="nanacoin-api"\s+content="[^"]*"\s*\/?\s*>/;
      if (!tag.test(html)) throw new Error('Missing API default meta tag');
      data = Buffer.from(html.replace(tag, '<meta name="nanacoin-api" content="">'));
    }
    const id = entries.length;
    writeFileSync(resolve(output, `${id}.raw`), data);
    const compressed = gzipSync(data, { level: 9 });
    writeFileSync(resolve(output, `${id}.gz`), compressed);
    const hash = createHash('sha256').update(data).digest('hex');
    const literalPath = (suffix) => JSON.stringify(resolve(output, `${id}.${suffix}`).replaceAll('\\', '/'));
    entries.push(`Asset { path: ${JSON.stringify('/' + name)}, mime: ${JSON.stringify(types[extname(name)])}, raw: include_bytes!(${literalPath('raw')}), gzip: include_bytes!(${literalPath('gz')}), etag: ${JSON.stringify('W/"' + hash + '"')}, immutable: ${/-[A-Za-z0-9_-]{8,}\.(js|css)$/.test(name)} }`);
  }
}
walk(input);
if (!entries.some(e => e.includes('path: "/index.html"'))) throw new Error('Missing index.html');
const embedded = name => JSON.stringify(resolve(output, name).replaceAll('\\', '/'));
writeFileSync(resolve(output, 'assets.rs'), `// Generated by scripts/bundle-web.mjs\nstatic TRUST_HTML: &[u8] = include_bytes!(${embedded('trust.html')});\nstatic CA_CERT: &[u8] = include_bytes!(${embedded('home-ca.der')});\nstatic ASSETS: &[Asset] = &[\n${entries.join(',\n')}\n];\n`);
console.log(`Bundled ${entries.length} assets (identity + gzip) for same-origin hosting.`);
